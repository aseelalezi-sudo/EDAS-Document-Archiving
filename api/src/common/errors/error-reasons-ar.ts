function parameterized(message: string): string | undefined {
  for (const rule of TEMPLATE_REASONS) if (message.startsWith(rule.prefix)) return rule.ar(message.slice(rule.prefix.length));
  for (const rule of SUFFIX_REASONS) {
    if (message.endsWith(rule.suffix)) return rule.ar(message.slice(0, -rule.suffix.length));
  }
  return undefined;
}

export function arabicReason(message: string | undefined, status = 400): string {
  const trimmed = message?.trim();
  if (!trimmed) return GENERIC_REASONS[status] ?? "تعذّر إتمام العملية";
  const exact = EXACT_REASONS[trimmed];
  if (exact) return exact;
  return parameterized(trimmed) ?? GENERIC_REASONS[status] ?? "تعذّر إتمام العملية";
}

export function hasArabicReason(message: string): boolean {
  return EXACT_REASONS[message] !== undefined || parameterized(message) !== undefined;
}
