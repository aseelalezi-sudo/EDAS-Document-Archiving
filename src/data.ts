export function deptName(id: string, lang: "ar" | "en") {
  if (!id) return "—";
  const d = liveDepartments.find((x) => x.id === id) ?? departments.find((x) => x.id === id);
  return d ? (lang === "en" ? d.nameEn : d.name) : id;
}
